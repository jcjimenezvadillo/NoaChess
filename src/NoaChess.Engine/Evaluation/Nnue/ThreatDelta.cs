using NoaChess.Core;

namespace NoaChess.Engine.Evaluation.Nnue;

// Which threat features a move can possibly change.
//
// WHY THIS EXISTS. A full threat refresh costs 3000-3700 ns per node against
// about 1000 for an entire NNUE evaluation, so a net with threat features
// cannot ship behind one. Measured over 168 legal moves, 36.8 features are
// active on average and only 6.2 of them change: 83% survive a move untouched.
// An incremental update therefore replaces about 37 row additions with about 6.
//
// THE COMPLETENESS ARGUMENT, which is the whole design and is worth stating
// because a delta that misses one feature corrupts the accumulator silently and
// forever. A feature is a pair (attacker on a, target on t) where a attacks t.
// Let S be the squares whose contents change - {from, to} for an ordinary move,
// plus the rook's two squares when castling and the captured pawn's square en
// passant. A feature can only change if:
//
//   1. a is in S            the attacker itself moved, appeared or vanished
//   2. t is in S            the target moved, vanished or changed type
//   3. the ray a->t crosses S   a slider's line opened or closed
//
// Case 2 puts the attacker in attackersTo(t) for some t in S. Case 3 also does,
// and this is the part worth checking rather than assuming: for a slider on a
// whose ray passes through s, if s was occupied and became empty the slider
// attacked s before (a slider attacks the blocker it stops on); if s was empty
// and became occupied the slider attacked s before as well (a slider attacks
// every empty square along its ray). Either way it is in attackersTo(s). So
//
//     affected = { pieces standing on S } U { attackersTo(s) : s in S }
//
// evaluated both BEFORE and AFTER the move, and that is complete.
//
// THE EXCEPTION THE DESIGN NOTE MISSED. One threat relation is not an attack:
// a pawn stopped by a pawn directly in front of it. A pawn does not attack the
// square ahead, so attackersTo never returns it, and a pawn appearing or
// vanishing on that square would change a feature this set does not contain.
// The pawn one square behind each member of S is therefore added explicitly.
public static class ThreatDelta
{
    // At most four squares change: castling moves two pieces.
    public const int MaxChangedSquares = 4;

    // Squares whose occupancy or contents the move alters. Call it with the
    // board in its position BEFORE the move.
    public static int ChangedSquares(Board board, Move move, Span<int> squares)
    {
        int count = 0;
        squares[count++] = move.From;
        squares[count++] = move.To;

        switch (move.Flag)
        {
            case MoveFlag.KingCastle:
            case MoveFlag.QueenCastle:
            {
                // The rook moves too, and its own threats plus everything
                // aimed through its two squares change with it.
                int rank = move.From & ~7;
                bool kingSide = move.Flag == MoveFlag.KingCastle;
                squares[count++] = rank + (kingSide ? 7 : 0);
                squares[count++] = rank + (kingSide ? 5 : 3);
                break;
            }

            case MoveFlag.EnPassant:
                // The captured pawn is NOT on the destination square, which is
                // the one case where "the move empties from and fills to" is a
                // wrong description of what happened.
                squares[count++] = board.SideToMove == Color.White
                    ? move.To - 8
                    : move.To + 8;
                break;
        }

        return count;
    }

    // Squares holding a piece whose own threat set can change. Evaluate on both
    // sides of the move and union the results: a piece that only exists after
    // the move cannot be found before it.
    public static ulong AffectedAttackers(Board board, ReadOnlySpan<int> changed)
    {
        ulong occupied = board.AllOccupancy;
        ulong whitePawns = board.Pieces(Color.White, PieceType.Pawn);
        ulong blackPawns = board.Pieces(Color.Black, PieceType.Pawn);
        ulong affected = 0;

        foreach (int square in changed)
        {
            affected |= 1UL << square;
            affected |= AttackersTo(board, square, occupied);

            // The blocked-pawn relation, which is not an attack: a white pawn
            // one square below, or a black pawn one square above, has this
            // square as the target it is stopped by.
            if (square >= 8)
                affected |= (1UL << (square - 8)) & whitePawns;
            if (square <= 55)
                affected |= (1UL << (square + 8)) & blackPawns;
        }

        return affected & occupied;
    }

    // Every threat feature generated BY the pieces standing on 'attackers'.
    // Same relations as a full refresh, restricted to those attackers.
    public static int CollectFrom(Board board, Color perspective, ulong attackers,
                                  Span<int> destination)
    {
        int kingSquare = board.KingSquare(perspective);
        ulong occupied = board.AllOccupancy;
        int count = 0;

        // Filtered against THIS position's occupancy, and that is required
        // rather than tidy. The caller unions the affected set across the move,
        // so it legitimately contains squares that are occupied on one side of
        // it and empty on the other. Asking the index for the threats of a
        // piece that is not there reads PieceTypeAt of an empty square, and the
        // schema lookup then runs off the end of its table.
        attackers &= occupied;

        while (attackers != 0)
        {
            int from = Bitboard.PopLsb(ref attackers);
            Color colour = board.ColorAt(from);
            PieceType type = board.PieceTypeAt(from);

            if (type == PieceType.Pawn)
            {
                AddPawn(board, perspective, kingSquare, colour, from, destination, ref count);
                continue;
            }

            if (type == PieceType.King)
                continue; // Kings generate no threat features.

            ulong attacks = type switch
            {
                PieceType.Knight => Attacks.Knight(from),
                PieceType.Bishop => Attacks.Bishop(from, occupied),
                PieceType.Rook => Attacks.Rook(from, occupied),
                _ => Attacks.Queen(from, occupied),
            } & occupied;

            while (attacks != 0)
            {
                int to = Bitboard.PopLsb(ref attacks);
                // No target mask here: Index rejects every pair the schema does
                // not record, and every geometry that is not a real attack, so
                // the occupancy mask above is all the filtering needed.
                int index = ThreatFeatureIndex.Index(perspective, kingSquare, colour, type, from,
                                                     board.ColorAt(to), board.PieceTypeAt(to), to);
                if (index >= 0)
                    destination[count++] = index;
            }
        }

        return count;
    }

    // One pawn's relations: the two capture diagonals and the blocked push.
    // Mirrors the bulk shifts of a full refresh, including their file guards -
    // without those a pawn on the a-file would wrap around to the h-file and
    // produce a feature for an attack that does not exist.
    private static void AddPawn(Board board, Color perspective, int kingSquare, Color colour,
                                int from, Span<int> destination, ref int count)
    {
        ulong occupied = board.AllOccupancy;
        int file = from & 7;
        bool white = colour == Color.White;

        // Three candidate targets, then one loop: a local function would be
        // tidier but cannot capture a Span or a ref parameter.
        Span<int> candidates = stackalloc int[3];
        int candidateCount = 0;

        if (white ? file != 7 : file != 0)
            candidates[candidateCount++] = white ? from + 9 : from - 9;
        if (white ? file != 0 : file != 7)
            candidates[candidateCount++] = white ? from + 7 : from - 7;

        // Blocked by a pawn directly in front. The target must be a pawn, of
        // either colour: what the relation records is being stopped, not by whom.
        int ahead = white ? from + 8 : from - 8;
        if (ahead is >= 0 and < 64
            && (occupied & (1UL << ahead)) != 0
            && board.PieceTypeAt(ahead) == PieceType.Pawn)
            candidates[candidateCount++] = ahead;

        for (int i = 0; i < candidateCount; i++)
        {
            int to = candidates[i];
            if (to is < 0 or > 63 || (occupied & (1UL << to)) == 0)
                continue;
            int index = ThreatFeatureIndex.Index(perspective, kingSquare, colour, PieceType.Pawn,
                                                 from, board.ColorAt(to), board.PieceTypeAt(to), to);
            if (index >= 0)
                destination[count++] = index;
        }
    }

    // Local copy rather than a call into the static exchange evaluator: that one
    // is private there, and the threat delta wants exactly this set including
    // kings, which SEE also includes. Kept side by side deliberately - sharing
    // it would tie a hot evaluation path to a hot search path for four lines.
    private static ulong AttackersTo(Board board, int square, ulong occupied)
    {
        ulong attackers =
              (Attacks.Pawn(Color.Black, square) & board.Pieces(Color.White, PieceType.Pawn))
            | (Attacks.Pawn(Color.White, square) & board.Pieces(Color.Black, PieceType.Pawn))
            | (Attacks.Knight(square) & (board.Pieces(Color.White, PieceType.Knight)
                                       | board.Pieces(Color.Black, PieceType.Knight)))
            | (Attacks.King(square) & (board.Pieces(Color.White, PieceType.King)
                                     | board.Pieces(Color.Black, PieceType.King)));

        ulong bishopLike = board.Pieces(Color.White, PieceType.Bishop)
                         | board.Pieces(Color.Black, PieceType.Bishop)
                         | board.Pieces(Color.White, PieceType.Queen)
                         | board.Pieces(Color.Black, PieceType.Queen);
        attackers |= Attacks.Bishop(square, occupied) & bishopLike;

        ulong rookLike = board.Pieces(Color.White, PieceType.Rook)
                       | board.Pieces(Color.Black, PieceType.Rook)
                       | board.Pieces(Color.White, PieceType.Queen)
                       | board.Pieces(Color.Black, PieceType.Queen);
        attackers |= Attacks.Rook(square, occupied) & rookLike;

        return attackers;
    }
}
